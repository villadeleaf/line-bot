const API_KEY = (process.env.ANTHROPIC_API_KEY || "").replace(/[^A-Za-z0-9_-]/g, "");
const anthropic = new Anthropic({ apiKey: API_KEY, maxRetries: 4 });

// ---- ข้อมูลวันที่ปัจจุบัน (ช่วยบอทคิดราคาตามฤดู/วัน) ----
const THAI_DAYS = ["อาทิตย์", "จันทร์", "อังคาร", "พุธ", "พฤหัสบดี", "ศุกร์", "เสาร์"];
const THAI_MONTHS = ["มกราคม", "กุมภาพันธ์", "มีนาคม", "เมษายน", "พฤษภาคม", "มิถุนายน", "กรกฎาคม", "สิงหาคม", "กันยายน", "ตุลาคม", "พฤศจิกายน", "ธันวาคม"];

function currentContext() {
  const now = new Date();
  const m = now.getMonth(); // 0=ม.ค. ... 11=ธ.ค.
  const season = m >= 4 && m <= 8 ? "Low" : "High"; // พ.ค.(4)–ก.ย.(8) = Low
  const dateStr = `วัน${THAI_DAYS[now.getDay()]} ที่ ${now.getDate()} ${THAI_MONTHS[m]} ${now.getFullYear() + 543}`;
  return `ข้อมูลเวลาปัจจุบัน (ใช้คำนวณราคาให้ตรงช่วง): วันนี้คือ ${dateStr} → อยู่ในช่วง ${season} season เมื่อลูกค้าพูดว่า "วันนี้/พรุ่งนี้/เสาร์นี้/สุดสัปดาห์นี้" ให้อิงจากวันนี้เป็นหลัก`;
}

// ---- สร้างคำตอบจากประวัติสนทนา ----
//  extraKnowledge = ความรู้เพิ่มเติมที่แอดมินสอน (จาก Google Sheet) แนบท้าย (ไม่แคช เพราะเปลี่ยนได้)
async function generateReply(history, extraKnowledge = "") {
  const system = [
    {
      type: "text",
      text: SYSTEM_PROMPT,
      cache_control: { type: "ephemeral" }, // ประหยัดค่าใช้จ่ายจากข้อมูลที่ส่งซ้ำ
    },
    { type: "text", text: currentContext() }, // วันที่ (ไม่แคช เพราะเปลี่ยนทุกวัน)
  ];
  if (extraKnowledge) system.push({ type: "text", text: extraKnowledge });

  // ถ้าลูกค้าถามเรื่องอาหาร/เมนู → แนบ "เมนูรายจาน" ที่แยกออกไป (โหลดตอนถาม = ประหยัด token ข้อความอื่น ๆ)
  const lastUserMsg = [...history].reverse().find((m) => m.role === "user");
  const lastText =
    lastUserMsg && typeof lastUserMsg.content === "string" ? lastUserMsg.content : "";
  const foodRe = /อาหาร|เมนู|à ?la ?carte|กับข้าว|ของกิน|จะกิน|อยากกิน|สั่งอาหาร|สั่งกับข้าว|หิว|เครื่องดื่ม|กาแฟ|ค็อกเทล|ม็อกเทล|เบียร์|ชาไทย|น้ำผลไม้|ปิ้งย่าง|มีอะไรกิน|กินอะไร|ราคาอาหาร|\bmenu\b|\bfood\b|\bdrink\b/i;
  if (menuKnowledge && foodRe.test(lastText)) {
    system.push({
      type: "text",
      text: "เมนูอาหาร/เครื่องดื่มรายจานพร้อมราคา (ตอบเรื่องเมนูจากนี่ได้เลย):\n" + menuKnowledge,
    });
  }

  // ลองเรียก AI ใหม่เองอีกชั้น เผื่อ API overload/สะดุด (529/429/5xx) — หน่วงเพิ่มขึ้นเรื่อย ๆ
  let response;
  let lastErr;
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      response = await anthropic.messages.create({
        model: MODEL,
        max_tokens: 2000,
        system,
        messages: history,
      });
      lastErr = null;
      break;
    } catch (err) {
      lastErr = err;
      const status = err && err.status;
      const retriable = status === 429 || status === 529 || (status >= 500 && status < 600) || err.name === "APIConnectionError";
      if (!retriable || attempt === 2) throw err;
      await new Promise((r) => setTimeout(r, 1500 * (attempt + 1))); // 1.5s, 3s
    }
  }
  if (!response) throw lastErr;

  return response.content
    .filter((b) => b.type === "text")
    .map((b) => b.text)
    .join("\n")
    .trim();
}

module.exports = { MODEL, SYSTEM_PROMPT, generateReply };
