//  Phase 3 — ดึง "ช่วงวันเข้าพัก" จากบทสนทนา เพื่อไปเช็คห้องว่างจริงจากระบบเฮีย
//  รองรับวันแบบคน ๆ ("ศุกร์นี้", "29-30", "สิ้นเดือน") — อิงวันที่ปัจจุบัน
// ============================================================
async function extractAvailabilityQuery(history) {
  const recent = history
    .slice(-6)
    .map((m) => `${m.role === "user" ? "ลูกค้า" : "น้องลีฟ"}: ${typeof m.content === "string" ? m.content : ""}`)
    .join("\n");
  const todayCE = new Date(Date.now() + 7 * 3600 * 1000).toISOString().slice(0, 10); // วันนี้เวลาไทย แบบ ค.ศ.
  const sys = `${currentContext()}
วันนี้แบบ ค.ศ. (Gregorian) คือ ${todayCE}
คุณช่วยระบบจองรีสอร์ทตีความบทสนทนาล่าสุด: ลูกค้ากำลังถามห้องว่าง/จะจอง "ช่วงวันไหน"
- ถ้าบทสนทนาระบุ "วันเข้าพัก" ได้ (แม้แค่วันเดียว เช่น "ศุกร์นี้" "31 ก.ค." "วันแม่") ให้แปลงเป็นวันที่จริง (อิงวันนี้ เลือกปีที่สมเหตุสมผลที่สุด อนาคตเสมอ) แล้วตอบ ask:true เสมอ
- checkout = วันเช็คเอาท์ (ไม่นับเป็นคืนพัก) · ⚠️ ถ้าลูกค้า "ไม่ได้บอกจำนวนคืน" → ถือว่าพัก 1 คืน (checkout = วันถัดจาก checkin) เพื่อเช็คห้องว่างของวันนั้นได้ · ถ้าบอกจำนวนคืน/ช่วงวันชัด ให้ใช้ตามนั้น
- ตอบ {"ask":false} เฉพาะเมื่อ "ไม่รู้วันเข้าพักเลย" (ลูกค้ายังไม่เอ่ยวันใด ๆ) หรือไม่ได้ถามเรื่องห้องว่าง/ราคา/จองเท่านั้น
- ⚠️ ปีต้องเป็น "ค.ศ." เท่านั้น (เช่น ${todayCE.slice(0, 4)}) ห้ามตอบเป็น พ.ศ. เด็ดขาด — ถ้าลูกค้าพูดปี พ.ศ. ให้ลบ 543 ก่อน
ตอบ JSON บรรทัดเดียวเท่านั้น:
{"ask":true,"checkin":"YYYY-MM-DD","checkout":"YYYY-MM-DD"}
หรือถ้าไม่รู้วันเข้าพักเลย: {"ask":false}`;
  const response = await anthropic.messages.create({
    model: MODEL, // ใช้ Sonnet เหมือนขั้นเรียบเรียง — คงคุณภาพ/ความแม่นวันที่ (ยอมช้ากว่า พึ่ง timeout 50วิ ฝั่งเฮีย)
    max_tokens: 200,
    system: [{ type: "text", text: sys }],
    messages: [{ role: "user", content: recent || "-" }],
  });
  const text = response.content.filter((b) => b.type === "text").map((b) => b.text).join("").trim();
  try {
    const m = text.match(/\{[\s\S]*\}/);
    const obj = JSON.parse(m ? m[0] : text);
    if (obj && obj.ask && /^\d{4}-\d{2}-\d{2}$/.test(obj.checkin || "") && /^\d{4}-\d{2}-\d{2}$/.test(obj.checkout || "")) {
      return { ask: true, checkin: obj.checkin, checkout: obj.checkout };
    }
  } catch (e) {
    console.error("extractAvailabilityQuery parse:", e.message, "| raw:", text.slice(0, 120));
  }
  return { ask: false };
}

