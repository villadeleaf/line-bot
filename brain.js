const THAI_DAYS = ["อาทิตย์", "จันทร์", "อังคาร", "พุธ", "พฤหัสบดี", "ศุกร์", "เสาร์"];
const THAI_MONTHS = ["มกราคม", "กุมภาพันธ์", "มีนาคม", "เมษายน", "พฤษภาคม", "มิถุนายน", "กรกฎาคม", "สิงหาคม", "กันยายน", "ตุลาคม", "พฤศจิกายน", "ธันวาคม"];

function currentContext() {
  const now = new Date(Date.now() + 7 * 3600 * 1000); // เวลาไทย (UTC+7) — Render รันบน UTC
  const dow = now.getUTCDay(); // 0=อา ... 6=ส (อ่านแบบ UTC เพราะ shift +7 แล้ว)
  const m = now.getUTCMonth();
  const season = m >= 4 && m <= 8 ? "Low" : "High"; // พ.ค.(4)–ก.ย.(8) = Low
  const hh = now.getUTCHours(), mm = now.getUTCMinutes();
  const dateStr = `วัน${THAI_DAYS[dow]} ที่ ${now.getUTCDate()} ${THAI_MONTHS[m]} ${now.getUTCFullYear() + 543}`;
  const timeStr = `${String(hh).padStart(2, "0")}:${String(mm).padStart(2, "0")}`;
  // เวลาทำการแอดมิน: จ-ศ 10:00–22:30 · ส-อา(เสาร์-อาทิตย์) 11:00–23:00
  const mins = hh * 60 + mm;
  const satSun = dow === 6 || dow === 0;
  const openMin = satSun ? 11 * 60 : 10 * 60;
  const closeMin = satSun ? 23 * 60 : 22 * 60 + 30;
  const adminOpen = mins >= openMin && mins <= closeMin;
  return (
    `ข้อมูลเวลาปัจจุบัน (เวลาไทย): วันนี้คือ ${dateStr} เวลา ${timeStr} น. → อยู่ในช่วง ${season} season · เมื่อลูกค้าพูดว่า "วันนี้/พรุ่งนี้/เสาร์นี้/สุดสัปดาห์นี้" ให้อิงจากวันนี้เป็นหลัก\n` +
    `สถานะเวลาทำการแอดมิน (จ-ศ 10:00–22:30 · ส-อา 11:00–23:00): ตอนนี้ ${adminOpen ? "อยู่ในเวลาทำการ ✅" : "นอกเวลาทำการ ⛔"}`
  );
}

